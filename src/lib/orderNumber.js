// ตรวจว่าค่านี้เป็นเลขที่ใบสั่งซื้อที่ใช้งานได้จริงหรือไม่
// บาง PDF (เช่นใบสั่งของคลินิกที่ไม่มีเลขที่ใบสั่งซื้อเครื่องมือแพทย์) พิมพ์ "-" เป็นตัวคั่นว่างในช่องนี้แทนเลขจริง
// ใช้ตรวจสอบทั้งตอน parse PDF (UploadPDF.jsx) และตอนเช็คเลขที่ซ้ำในรายการใบสั่งซื้อ (Orders.jsx)
// เพื่อไม่ให้ค่าขยะแบบนี้ถูกจับว่าเป็นเลขที่จริง หรือถูกเข้าใจผิดว่าใบสั่งหลายใบมีเลขที่ซ้ำกัน
export function isJunkNumber(v) {
  return !v || !/[A-Za-z0-9ก-๙]{2,}/.test(v);
}
